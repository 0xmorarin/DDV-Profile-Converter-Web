import assert from "node:assert/strict";
import {inspectTimingFields,patchTimingFields} from "../js/time-tools.js";
const save = '{"GameInfo":{"Version":626},"LastDailyReset":"2026-11-01T05:00:00Z","World":{"NextWeatherCheck":"2026-11-01T00:41:28Z","RecurringEvents":{"0":{"FishSpawningInVillage":{"RecurringEventItemID":2010200014,"NextOccurrence":"2026-11-01T00:19:13.742392200Z","EndDate":null}},"5":{"ItemSpawning":{"RecurringEventItemID":2010000096,"NextOccurrence":"2126-08-20T00:00:00Z","LastOccurrence":"2026-07-30T03:31:43Z"}},"8":{"ChooseVillageArea":{"RecurringEventItemID":4,"NextOccurrence":"2026-11-02T00:10:51Z"}}}},"BigInt":9007199254740993123456789}';
const r = inspectTimingFields(save,Date.UTC(2026,10,1));
assert.equal(r.schema,"626");
assert.equal(r.events.length,3);
assert.equal(r.diagnostic.length,2);
const fish=r.events.find(x=>x.eventKey==="0"), sentinel=r.events.find(x=>x.eventKey==="5");
assert.equal(fish.editable,true);
assert.equal(sentinel.classification,"long-range");
assert.equal(sentinel.editable,false);
assert.equal(r.events.find(x=>x.eventKey==="8").editable,false);
const after=patchTimingFields(save,[{pointer:fish.pointer,expected:fish.time,value:"2026-11-04T02:30:00Z"}]);
assert.equal(after.changes.length,1);
assert.equal(after.jsonText.replace("2026-11-04T02:30:00Z",fish.time),save);
assert.ok(after.jsonText.includes("9007199254740993123456789"));
assert.throws(()=>patchTimingFields(save,[{pointer:sentinel.pointer,expected:sentinel.time,value:"2026-11-01T00:00:00Z"}]),/not permitted/);
assert.throws(()=>patchTimingFields(save,[{pointer:fish.pointer,expected:"2026-11-03T00:00:00Z",value:"2026-11-04T02:30:00Z"}]),/mismatch/);
assert.throws(()=>patchTimingFields(save,[{pointer:fish.pointer,expected:fish.time,value:"2126-11-04T02:30:00Z"}]),/Invalid/);
assert.equal(inspectTimingFields(save.replace('"Version":626','"Version":999')).canWriteSchema,false);
const duplicate=save.replace('"NextOccurrence":"2026-11-01T00:19:13.742392200Z"','"NextOccurrence":"2026-11-01T00:19:13.742392200Z","NextOccurrence":"2026-11-01T00:19:13.742392200Z"');
assert.throws(()=>patchTimingFields(duplicate,[{pointer:fish.pointer,expected:fish.time,value:"2026-11-04T02:30:00Z"}]),/Duplicate JSON key/);
console.log("Time tools tests passed.");
